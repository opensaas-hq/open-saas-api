import { describe, expect, test } from "bun:test";
import { withRawTransaction } from "@opensaas/database";
import {
  APP_ORIGIN,
  createLogCapture,
  createTenant,
  createTestApp,
  hasTestDatabase,
  jsonHeaders,
} from "./support/app";

/**
 * The cross-cutting middleware pipeline (§4.5).
 *
 * These tests cover the guarantees every response must give: a correlation id,
 * the security headers, a body-size limit, a rate limit with `Retry-After`, a
 * CORS allowlist and exactly one structured access-log line.
 */
const describeIfDb = hasTestDatabase() ? describe : describe.skip;

/** A request id generated by the app looks like a UUID. */
const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

describe("Apps/API - Cross-cutting middleware pipeline (§4.5)", () => {
  test("every response carries a request id and the security headers", async () => {
    const { app } = createTestApp();

    const res = await app.fetch(new Request(`${APP_ORIGIN}/api/health`));

    expect(res.headers.get("x-request-id")).toMatch(UUID_PATTERN);
    expect(res.headers.get("x-content-type-options")).toBe("nosniff");
    expect(res.headers.get("x-frame-options")).toBe("SAMEORIGIN");
    expect(res.headers.get("strict-transport-security")).toContain("max-age=");
  });

  test("the headers are present on the auth surface and on unknown routes", async () => {
    const { app } = createTestApp();

    const auth = await app.fetch(
      new Request(`${APP_ORIGIN}/api/auth/get-session`, {
        headers: jsonHeaders(),
      }),
    );
    const unknown = await app.fetch(
      new Request(`${APP_ORIGIN}/api/does-not-exist`),
    );

    for (const res of [auth, unknown]) {
      expect(res.headers.get("x-request-id")).toMatch(UUID_PATTERN);
      expect(res.headers.get("x-content-type-options")).toBe("nosniff");
    }
  });

  test("a client-provided request id is echoed back", async () => {
    const { app } = createTestApp();

    const res = await app.fetch(
      new Request(`${APP_ORIGIN}/api/health`, {
        headers: { "x-request-id": "correlation-42" },
      }),
    );

    expect(res.headers.get("x-request-id")).toBe("correlation-42");
  });

  test("an unsafe request id is replaced by a generated one", async () => {
    const { app } = createTestApp();

    const res = await app.fetch(
      new Request(`${APP_ORIGIN}/api/health`, {
        headers: { "x-request-id": "not a safe id" },
      }),
    );

    expect(res.headers.get("x-request-id")).toMatch(UUID_PATTERN);
  });

  test("an oversized body is refused with a 413", async () => {
    const { app } = createTestApp({ BODY_SIZE_LIMIT_BYTES: 64 });

    const res = await app.fetch(
      new Request(`${APP_ORIGIN}/api/v1/registration`, {
        method: "POST",
        headers: jsonHeaders(),
        body: JSON.stringify({ padding: "x".repeat(512) }),
      }),
    );

    expect(res.status).toBe(413);
    const body = (await res.json()) as { error: { code: string } };
    expect(body.error.code).toBe("PAYLOAD_TOO_LARGE");
  });

  test("the registration endpoint is rate limited with a retry-after header", async () => {
    const capture = createLogCapture();
    const { app } = createTestApp(
      {
        LOG_LEVEL: "info",
        WRITE_RATE_LIMIT_ENABLED: true,
        WRITE_RATE_LIMIT_MAX: 2,
        WRITE_RATE_LIMIT_WINDOW_S: 60,
      },
      { destination: capture.destination },
    );

    // The payload is invalid on purpose: the limiter must count the request
    // before the route is reached, so the rejection does not depend on the
    // registration flow itself.
    const attempt = async () =>
      await app.fetch(
        new Request(`${APP_ORIGIN}/api/v1/registration`, {
          method: "POST",
          headers: jsonHeaders(),
          body: JSON.stringify({}),
        }),
      );

    const first = await attempt();
    const second = await attempt();
    const third = await attempt();

    expect(first.status).not.toBe(429);
    expect(second.status).not.toBe(429);
    expect(third.status).toBe(429);

    const retryAfter = Number(third.headers.get("retry-after"));
    expect(Number.isInteger(retryAfter)).toBe(true);
    expect(retryAfter).toBeGreaterThan(0);
    expect(retryAfter).toBeLessThanOrEqual(60);

    // The access log reports the status the client actually received.
    const accessLines = capture.lines
      .map((line) => JSON.parse(line) as Record<string, unknown>)
      .filter((line) => line.msg === "request completed");
    const requestId = third.headers.get("x-request-id");
    const line = accessLines.find((entry) => entry.requestId === requestId);
    expect(line?.status).toBe(429);
  });

  test("the login endpoint is rate limited with a retry-after header", async () => {
    const { app } = createTestApp({
      WRITE_RATE_LIMIT_ENABLED: true,
      WRITE_RATE_LIMIT_MAX: 1,
      WRITE_RATE_LIMIT_WINDOW_S: 30,
    });

    const attempt = async () =>
      await app.fetch(
        new Request(`${APP_ORIGIN}/api/auth/sign-in/email`, {
          method: "POST",
          headers: jsonHeaders(),
          body: JSON.stringify({
            email: "nobody@example.com",
            password: "wrong-password",
          }),
        }),
      );

    const first = await attempt();
    const second = await attempt();

    expect(first.status).not.toBe(429);
    expect(second.status).toBe(429);
    expect(Number(second.headers.get("retry-after"))).toBeGreaterThan(0);
  });

  test("a trusted origin is allowed and an unknown origin is blocked", async () => {
    const { app } = createTestApp({
      TRUSTED_ORIGINS: "http://allowed.example",
    });

    const allowed = await app.fetch(
      new Request(`${APP_ORIGIN}/api/health`, {
        headers: { origin: "http://allowed.example" },
      }),
    );
    const blocked = await app.fetch(
      new Request(`${APP_ORIGIN}/api/health`, {
        headers: { origin: "http://evil.example" },
      }),
    );

    expect(allowed.headers.get("access-control-allow-origin")).toBe(
      "http://allowed.example",
    );
    expect(blocked.headers.get("access-control-allow-origin")).toBeNull();
  });

  test("exactly one structured access-log line is emitted per request", async () => {
    const capture = createLogCapture();
    const { app } = createTestApp(
      { LOG_LEVEL: "info" },
      { destination: capture.destination },
    );

    const res = await app.fetch(new Request(`${APP_ORIGIN}/api/health`));
    const requestId = res.headers.get("x-request-id");

    const accessLines = capture.lines
      .map((line) => JSON.parse(line) as Record<string, unknown>)
      .filter((line) => line.msg === "request completed");

    const linesOfRequest = accessLines.filter(
      (line) => line.requestId === requestId,
    );

    expect(linesOfRequest.length).toBe(1);

    const line = linesOfRequest[0];
    expect(line.method).toBe("GET");
    expect(line.path).toBe("/api/health");
    expect(line.status).toBe(res.status);
    expect(typeof line.durationMs).toBe("number");
    expect(line.requestId).toBe(requestId);
  });
});

describeIfDb(
  "Apps/API - Cross-cutting middleware pipeline, with a tenant",
  () => {
    test("a bulk payload over the maximum is refused with a 422", async () => {
      await withRawTransaction(async (tx) => {
        await tx.execute(
          `TRUNCATE TABLE registration_code, waitlist_entry, "member", "organization",
         "account", "session", "verification", "user", branches, contacts, audit_log
         RESTART IDENTITY CASCADE`,
        );
      });

      const { app } = createTestApp({ BULK_MAX_CONTACTS: 2 });
      const tenant = await createTenant(app, {
        email: "bulk-max@example.com",
        password: "password123",
        name: "Bulk Max",
        slug: `bulk-max-${Date.now().toString(36)}`,
      });

      const res = await app.fetch(
        new Request(`${APP_ORIGIN}/api/v1/contacts/bulk`, {
          method: "POST",
          headers: jsonHeaders(tenant.cookie),
          body: JSON.stringify({
            contacts: [{ name: "One" }, { name: "Two" }, { name: "Three" }],
          }),
        }),
      );

      expect(res.status).toBe(422);
    });

    test("the access log carries the tenant id and never a personal datum", async () => {
      const capture = createLogCapture();
      const { app } = createTestApp(
        { LOG_LEVEL: "info" },
        { destination: capture.destination },
      );
      const tenant = await createTenant(app, {
        email: "access-log@example.com",
        password: "password123",
        name: "Access Log",
        slug: `access-log-${Date.now().toString(36)}`,
      });

      const res = await app.fetch(
        new Request(`${APP_ORIGIN}/api/v1/contacts`, {
          method: "POST",
          headers: jsonHeaders(tenant.cookie),
          body: JSON.stringify({
            name: "Personal Contact",
            email: "personal@example.com",
          }),
        }),
      );

      expect(res.status).toBe(201);

      const requestId = res.headers.get("x-request-id");
      const accessLines = capture.lines
        .map((line) => JSON.parse(line) as Record<string, unknown>)
        .filter((line) => line.msg === "request completed");
      const line = accessLines.find((entry) => entry.requestId === requestId);

      expect(line).toBeDefined();
      expect(line?.tenantId).toBe(tenant.organizationId);
      expect(line?.userId).toBe(tenant.userId);
      expect(line?.status).toBe(201);

      // The line carries identifiers and timings only: no body, no personal data.
      const emitted = capture.lines.join("\n");
      expect(emitted).not.toContain("personal@example.com");
      expect(emitted).not.toContain("Personal Contact");
      expect(emitted).not.toContain("access-log@example.com");
    });
  },
);
